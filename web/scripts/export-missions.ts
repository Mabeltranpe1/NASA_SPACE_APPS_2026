/**
 * Writes public/data/missions.json: the weights of every mission type per body and, for every
 * Moon/Mars site, the best score Earth has for each mission (a full scan of the comparator
 * database). The site panel uses it to say which missions a place suits ("suitable for") without
 * loading the 7 MB database. Run again after `python src/analog_api.py export-web`:
 *
 *   node --experimental-strip-types web/scripts/export-missions.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parseComparator, type ComparatorMeta } from '../src/comparator/compare.ts'
import { MISSION_IDS, missionReference, missionWeights } from '../src/comparator/missions.ts'

const dir = fileURLToPath(new URL('../public/data/comparator/', import.meta.url))
const meta = JSON.parse(readFileSync(dir + 'comparator.json', 'utf8')) as ComparatorMeta
const db = await parseComparator(meta, new Uint8Array(readFileSync(dir + 'earth.bin')))

const round = (v: number) => Math.round(v * 1e6) / 1e6
const weights = Object.fromEntries((['Moon', 'Mars'] as const).map((b) => [
  b, Object.fromEntries(MISSION_IDS.map((m) => [m, Object.fromEntries(Object.entries(missionWeights(meta, b, m)).map(([f, w]) => [f, round(w)]))])),
]))
const reference: Record<string, Record<string, number>> = {}
for (const s of meta.sites) {
  const ref = missionReference(db, s.values, s.body, 1)
  reference[s.id] = Object.fromEntries(MISSION_IDS.map((m) => [m, round(ref[m])]))
}
const out = {
  about: 'Mission types (web/src/comparator/missions.ts): weights per body and best Earth score per site and mission. Generated by web/scripts/export-missions.ts.',
  n_cells: db.n,
  missions: MISSION_IDS,
  weights,
  reference,
}
writeFileSync(fileURLToPath(new URL('../public/data/missions.json', import.meta.url)), JSON.stringify(out) + '\n')
console.log(`missions.json: ${meta.sites.length} sites x ${MISSION_IDS.length} missions`)
